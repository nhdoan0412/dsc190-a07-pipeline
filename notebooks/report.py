import marimo

__generated_with = "0.25.2"
app = marimo.App(width="medium")


@app.cell
def _():
    import marimo as mo
    import pandas as pd
    import matplotlib.pyplot as plt

    return mo, pd, plt


@app.cell
def _(mo):
    mo.md("""
    # Event Duration Analysis

    DSC 190 - Assignment 07

    This notebook analyzes event durations using the
    processed dataset generated by the DVC pipeline.

    The histogram shows the distribution of event
    durations in minutes.
    """)
    return


@app.cell
def _(mo, pd):
    data_path = (
        mo.notebook_dir().parent
        / "data"
        / "features"
        / "events.csv"
    )

    df = pd.read_csv(data_path)
    return (df,)


@app.cell
def _(df, mo):
    mo.md(f"""
    ## Dataset Summary

    - Total events: {len(df):,}
    - Mean duration: {df["duration_minutes"].mean():.2f} minutes
    - Median duration: {df["duration_minutes"].median():.2f} minutes
    - Maximum duration: {df["duration_minutes"].max():.2f} minutes
    """)
    return


@app.cell
def _(df, plt):
    fig, ax = plt.subplots(figsize=(8, 5))

    ax.hist(
        df["duration_minutes"],
        bins=20,
        edgecolor="black",
    )

    ax.set_title("Distribution of Event Durations")
    ax.set_xlabel("Duration (minutes)")
    ax.set_ylabel("Number of events")

    fig.tight_layout()

    fig
    return


if __name__ == "__main__":
    app.run()
